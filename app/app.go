// Package app reads the environment variables Clever Cloud defines for
// applications.
//
// Each variable has a constant holding its name and a getter reading it from
// the process environment. Getters parse the value the way the platform does:
// booleans accept 1/true/yes/on/enable/enabled (and their opposites), integers
// must be plain decimal numbers, choices must be one of the listed values.
// An unset variable yields its default value.
//
// String variables are read with Get<Name>. Every other type is read with
// MustGet<Name>, which panics when the value cannot be parsed: the platform
// refuses to deploy with such a value, so an application should not run with
// it either.
//
// The constants and getters live in variables.go, generated by
// gen/cmd/generate-app: do not edit it by hand.
package app

import (
	"fmt"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

// Entry is one occurrence of a variable that can be set several times, as
// NAME or NAME_<N>.
type Entry[T any] struct {
	// Key is the actual variable name, NAME or NAME_<N>.
	Key string
	// Index is N, 0 for NAME.
	Index int
	Value T
}

var (
	baseTrueValues  = []string{"1", "true", "yes", "on", "enable", "enabled"}
	baseFalseValues = []string{"0", "false", "no", "off", "disable", "disabled"}
)

func lookupString(def string, canBeEmpty bool, name string) string {
	v, ok := os.LookupEnv(name)
	if !ok {
		return def
	}
	v = strings.TrimSpace(v)
	if v == "" && !canBeEmpty {
		return def
	}
	return v
}

func lookupBool(def bool, extraTrue, extraFalse []string, name string) (bool, error) {
	return lookupBoolWith(def, append(slices.Clone(baseTrueValues), extraTrue...), append(slices.Clone(baseFalseValues), extraFalse...), name)
}

// lookupDisabler reads a variable that disables something: "off" or "disable"
// mean true (disabled), "on" or "enable" mean false.
func lookupDisabler(def bool, name string) (bool, error) {
	return lookupBoolWith(def,
		[]string{"1", "true", "yes", "off", "disable", "disabled"},
		[]string{"0", "false", "no", "on", "enable", "enabled"},
		name)
}

func lookupBoolWith(def bool, trueValues, falseValues []string, name string) (bool, error) {
	v, ok := os.LookupEnv(name)
	if !ok {
		return def, nil
	}
	return parseBool(name, v, trueValues, falseValues)
}

func parseBool(key, v string, trueValues, falseValues []string) (bool, error) {
	v = strings.ToLower(strings.TrimSpace(v))
	switch {
	case slices.Contains(trueValues, v):
		return true, nil
	case slices.Contains(falseValues, v):
		return false, nil
	}
	return false, fmt.Errorf("%s: %q must be one of [%s] (true) or [%s] (false)",
		key, v, strings.Join(trueValues, ", "), strings.Join(falseValues, ", "))
}

func lookupInt(def int, name string) (int, error) {
	v, ok := os.LookupEnv(name)
	if !ok {
		return def, nil
	}
	return parseInt(name, v)
}

// parseInt only accepts the canonical decimal form: no sign but "-", no
// leading zero, no spaces inside.
func parseInt(key, v string) (int, error) {
	v = strings.TrimSpace(v)
	n, err := strconv.Atoi(v)
	if err != nil || strconv.Itoa(n) != v {
		return 0, fmt.Errorf("%s: %q is not an integer", key, v)
	}
	return n, nil
}

// lookupChoice returns the value lowercased, after checking it is one of
// values.
func lookupChoice(def string, values []string, name string) (string, error) {
	v, ok := os.LookupEnv(name)
	if !ok {
		return def, nil
	}
	v = strings.ToLower(strings.TrimSpace(v))
	if !slices.Contains(values, v) {
		return "", fmt.Errorf("%s: %q must be one of [%s]", name, v, strings.Join(values, ", "))
	}
	return v, nil
}

// lookupMultiple collects every NAME and NAME_<N> variable, sorted by index.
func lookupMultiple[T any](parse func(key, value string) (T, error), name string) ([]Entry[T], error) {
	var entries []Entry[T]
	for _, kv := range os.Environ() {
		key, value, _ := strings.Cut(kv, "=")
		index, ok := multipleIndex(key, name)
		if !ok {
			continue
		}
		v, err := parse(key, value)
		if err != nil {
			return nil, err
		}
		entries = append(entries, Entry[T]{Key: key, Index: index, Value: v})
	}
	slices.SortStableFunc(entries, func(a, b Entry[T]) int { return a.Index - b.Index })
	return entries, nil
}

var indexSuffix = regexp.MustCompile(`^_(\d+)$`)

func multipleIndex(key, name string) (int, bool) {
	rest, ok := strings.CutPrefix(key, name)
	if !ok {
		return 0, false
	}
	if rest == "" {
		return 0, true
	}
	if m := indexSuffix.FindStringSubmatch(rest); m != nil {
		n, err := strconv.Atoi(m[1])
		return n, err == nil
	}
	return 0, false
}

func parseString(_, v string) (string, error) { return strings.TrimSpace(v), nil }

// must panics with err, the generated MustGet<Name> getters use it.
func must[T any](v T, err error) T {
	if err != nil {
		panic(err)
	}
	return v
}
