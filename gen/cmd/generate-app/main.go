// Package main generates the app package: one constant and one getter per
// environment variable Clever Cloud defines for applications, from a JSON
// description of those variables.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"unicode"

	. "github.com/dave/jennifer/jen"
)

// Variable is one entry of the JSON description, keyed by the variable name.
type Variable struct {
	Description    string   `json:"description"`
	Type           string   `json:"type"`
	Scopes         []string `json:"scopes"`
	Aliases        []string `json:"aliases"`
	Default        any      `json:"default"`
	Values         []string `json:"values"`
	TrueValues     []string `json:"true_values"`
	FalseValues    []string `json:"false_values"`
	ExpectedValues []string `json:"expected_values"`
	Example        string   `json:"example"`
	Multiple       bool     `json:"multiple"`
	Secret         bool     `json:"secret"`
	ReadOnly       bool     `json:"read_only"`
	Cleanup        bool     `json:"cleanup"`
	AlternativeOf  string   `json:"alternative_name"`
}

func main() {
	spec := flag.String("spec", "", "JSON description of the application environment variables (required)")
	output := flag.String("output", "../app/variables.go", "generated Go file")
	pkg := flag.String("package", "app", "package name of the generated file")
	flag.Parse()
	if *spec == "" {
		flag.Usage()
		os.Exit(2)
	}

	raw, err := os.ReadFile(*spec)
	if err != nil {
		log.Fatalf("read spec: %s", err)
	}
	vars := map[string]Variable{}
	if err := json.Unmarshal(raw, &vars); err != nil {
		log.Fatalf("parse spec: %s", err)
	}

	f, err := generate(*pkg, vars)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		log.Fatal(err)
	}
	if err := f.Save(*output); err != nil {
		log.Fatalf("write %s: %s", *output, err)
	}
	log.Printf("✅ %d variables written to %s", len(vars), *output)
}

func generate(pkg string, vars map[string]Variable) (*File, error) {
	f := NewFile(pkg)
	f.HeaderComment("Code generated by generate-app. DO NOT EDIT.")

	names := make([]string, 0, len(vars))
	for name := range vars {
		names = append(names, name)
	}
	slices.Sort(names)

	getters := map[string]string{}
	for _, name := range names {
		getter := getterName(name)
		if other, ok := getters[getter]; ok {
			return nil, fmt.Errorf("%s and %s both map to %s", other, name, getter)
		}
		getters[getter] = name
	}

	for _, name := range names {
		v := vars[name]
		if v.Type == "" {
			v.Type = "string"
		}

		comment(f, constComment(name, v))
		f.Const().Id(name).Op("=").Lit(name)
		f.Line()

		for _, alias := range v.Aliases {
			if _, ok := vars[alias]; ok {
				return nil, fmt.Errorf("%s: alias %s is also a variable", name, alias)
			}
			comment(f, fmt.Sprintf("%s is the former name of [%s].\n\nDeprecated: use [%s].", alias, name, name))
			f.Const().Id(alias).Op("=").Lit(alias)
			f.Line()
		}

		if err := getter(f, name, v); err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		f.Line()
	}

	if err := scopes(f, names, vars); err != nil {
		return nil, err
	}
	return f, nil
}

// scopes writes one Scope<Name> slice per scope, listing the variables of
// that scope, and the Scopes map indexing them by scope name.
func scopes(f *File, names []string, vars map[string]Variable) error {
	byScope := map[string][]string{}
	for _, name := range names {
		for _, scope := range vars[name].Scopes {
			if !slices.Contains(byScope[scope], name) {
				byScope[scope] = append(byScope[scope], name)
			}
		}
	}
	scopeNames := make([]string, 0, len(byScope))
	for scope := range byScope {
		scopeNames = append(scopeNames, scope)
	}
	slices.Sort(scopeNames)

	idents := map[string]string{}
	for _, scope := range scopeNames {
		ident := scopeIdent(scope)
		if other, ok := idents[ident]; ok {
			return fmt.Errorf("scopes %s and %s both map to %s", other, scope, ident)
		}
		idents[ident] = scope

		items := make([]Code, len(byScope[scope]))
		for i, name := range byScope[scope] {
			items[i] = Id(name)
		}
		comment(f, fmt.Sprintf("%s lists the variables of the %q scope.", ident, scope))
		f.Var().Id(ident).Op("=").Index().String().Custom(Options{Open: "{", Close: "}", Separator: ",", Multi: true}, items...)
		f.Line()
	}

	comment(f, "Scopes indexes the Scope<Name> slices by scope name.")
	f.Var().Id("Scopes").Op("=").Map(String()).Index().String().Values(DictFunc(func(d Dict) {
		for _, scope := range scopeNames {
			d[Lit(scope)] = Id(scopeIdent(scope))
		}
	}))
	return nil
}

// scopeIdent turns java-maven into ScopeJavaMaven.
func scopeIdent(scope string) string {
	return "Scope" + camel(strings.FieldsFunc(scope, func(r rune) bool { return r == '-' || r == '_' }))
}

// getter writes the Get<Name> function reading the variable, its aliases as
// a fallback.
func getter(f *File, name string, v Variable) error {
	lookupNames := []Code{Id(name)}
	for _, alias := range v.Aliases {
		lookupNames = append(lookupNames, Id(alias))
	}
	fn := getterName(name)
	doc := getterComment(fn, name, v)

	if v.Multiple {
		var parse Code
		var elem Code
		switch v.Type {
		case "string", "alternative":
			parse, elem = Id("parseString"), String()
		case "integer":
			parse, elem = Id("parseInt"), Int()
		default:
			return fmt.Errorf("multiple %s variables are not supported", v.Type)
		}
		comment(f, doc)
		f.Func().Id(fn).Params().Params(Index().Id("Entry").Types(elem), Error()).Block(
			Return(Id("lookupMultiple").Call(append([]Code{parse}, lookupNames...)...)),
		)
		return nil
	}

	switch v.Type {
	case "string", "alternative":
		def, err := defaultString(v.Default)
		if err != nil {
			return err
		}
		canBeEmpty := v.Default != nil && def == ""
		comment(f, doc)
		f.Func().Id(fn).Params().String().Block(
			Return(Id("lookupString").Call(append([]Code{Lit(def), Lit(canBeEmpty)}, lookupNames...)...)),
		)
	case "boolean", "disabler":
		def := false
		if v.Default != nil {
			b, ok := v.Default.(bool)
			if !ok {
				return fmt.Errorf("default %v is not a boolean", v.Default)
			}
			def = b
		}
		var call Code
		if v.Type == "disabler" {
			call = Id("lookupDisabler").Call(append([]Code{Lit(def)}, lookupNames...)...)
		} else {
			call = Id("lookupBool").Call(append([]Code{Lit(def), stringSlice(lower(v.TrueValues)), stringSlice(lower(v.FalseValues))}, lookupNames...)...)
		}
		comment(f, doc)
		f.Func().Id(fn).Params().Params(Bool(), Error()).Block(Return(call))
	case "integer":
		def := 0
		if v.Default != nil {
			n, ok := v.Default.(float64)
			if !ok || n != float64(int(n)) {
				return fmt.Errorf("default %v is not an integer", v.Default)
			}
			def = int(n)
		}
		comment(f, doc)
		f.Func().Id(fn).Params().Params(Int(), Error()).Block(
			Return(Id("lookupInt").Call(append([]Code{Lit(def)}, lookupNames...)...)),
		)
	case "choice":
		if len(v.Values) == 0 {
			return fmt.Errorf("choice without values")
		}
		def, err := defaultString(v.Default)
		if err != nil {
			return err
		}
		comment(f, doc)
		f.Func().Id(fn).Params().Params(String(), Error()).Block(
			Return(Id("lookupChoice").Call(append([]Code{Lit(strings.ToLower(def)), stringSlice(lower(v.Values))}, lookupNames...)...)),
		)
	default:
		return fmt.Errorf("unknown type %q", v.Type)
	}
	return nil
}

// constComment documents the variable above its constant: description, then
// the scopes and the facts a user needs before setting it.
func constComment(name string, v Variable) string {
	var b strings.Builder
	desc := strings.TrimSpace(v.Description)
	if desc == "" {
		desc = "No description."
	}
	b.WriteString(name + ": " + desc)

	var facts []string
	if len(v.Scopes) > 0 {
		facts = append(facts, "Scopes: "+strings.Join(v.Scopes, ", ")+".")
	}
	if v.Multiple {
		facts = append(facts, fmt.Sprintf("Can be set several times, as %s or %s_<N>.", name, name))
	}
	if v.ReadOnly {
		facts = append(facts, "Set by the platform: read it, do not set it.")
	}
	if v.Secret {
		facts = append(facts, "Holds a secret.")
	}
	if v.Cleanup {
		facts = append(facts, "The platform removes it from the application environment.")
	}
	if len(facts) > 0 {
		b.WriteString("\n\n" + strings.Join(facts, "\n"))
	}
	return b.String()
}

// getterComment says what the getter returns: type, accepted values, default
// and aliases.
func getterComment(fn, name string, v Variable) string {
	var lines []string
	if v.Multiple {
		lines = append(lines, fmt.Sprintf("%s returns every %s and %s_<N> variable, sorted by N.", fn, name, name))
	} else {
		lines = append(lines, fmt.Sprintf("%s returns the value of [%s].", fn, name))
	}

	switch v.Type {
	case "boolean":
		lines = append(lines, "It is true for "+strings.Join(append(slices.Clone([]string{"1", "true", "yes", "on", "enable", "enabled"}), lower(v.TrueValues)...), ", ")+
			"; false for "+strings.Join(append(slices.Clone([]string{"0", "false", "no", "off", "disable", "disabled"}), lower(v.FalseValues)...), ", ")+".")
	case "disabler":
		lines = append(lines, "It is true (disabled) for 1, true, yes, off, disable, disabled; false for 0, false, no, on, enable, enabled.")
	case "choice":
		lines = append(lines, "Accepted values: "+strings.Join(lower(v.Values), ", ")+".")
	case "alternative":
		if v.AlternativeOf != "" {
			lines = append(lines, "The value is a "+v.AlternativeOf+" version available on the platform.")
		}
	}
	if len(v.ExpectedValues) > 0 {
		lines = append(lines, "Expected values: "+strings.Join(v.ExpectedValues, ", ")+".")
	}
	if v.Example != "" {
		lines = append(lines, "Example: "+v.Example+".")
	}
	if v.Default != nil && !v.Multiple {
		lines = append(lines, fmt.Sprintf("Default: %v.", v.Default))
	}
	if len(v.Aliases) > 0 {
		aliases := strings.Join(v.Aliases, ", ")
		if v.Multiple {
			lines = append(lines, "The deprecated "+aliases+" variables are collected too.")
		} else {
			lines = append(lines, "When it is unset, the deprecated "+aliases+" is read instead.")
		}
	}
	return strings.Join(lines, "\n")
}

// comment writes text as // lines wrapped at 80 columns; jennifer would turn
// a multi-line comment into a /* */ block.
func comment(f *File, text string) {
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			f.Comment("")
			continue
		}
		for _, wrapped := range wrap(line, 77) {
			f.Comment(wrapped)
		}
	}
}

func wrap(line string, width int) []string {
	var lines []string
	var cur strings.Builder
	for _, word := range strings.Fields(line) {
		if cur.Len() > 0 && cur.Len()+1+len(word) > width {
			lines = append(lines, cur.String())
			cur.Reset()
		}
		if cur.Len() > 0 {
			cur.WriteByte(' ')
		}
		cur.WriteString(word)
	}
	if cur.Len() > 0 {
		lines = append(lines, cur.String())
	}
	return lines
}

// initialisms keep the Go casing of acronyms in getter names.
var initialisms = map[string]string{
	"API": "API", "APM": "APM", "CGI": "CGI", "CPU": "CPU", "DNS": "DNS",
	"FS": "FS", "HTTP": "HTTP", "ID": "ID", "IP": "IP", "IPV6": "IPv6",
	"JSON": "JSON", "MTA": "MTA", "NPM": "NPM", "PHP": "PHP", "SQL": "SQL",
	"SSH": "SSH", "TCP": "TCP", "TLS": "TLS", "URL": "URL", "VPN": "VPN",
}

// getterName turns CC_RUST_FEATURES into GetRustFeatures.
func getterName(name string) string {
	return "Get" + camel(strings.Split(strings.TrimPrefix(name, "CC_"), "_"))
}

// camel joins parts in CamelCase, keeping the Go casing of initialisms.
func camel(parts []string) string {
	var b strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		if initialism, ok := initialisms[strings.ToUpper(part)]; ok {
			b.WriteString(initialism)
			continue
		}
		r := []rune(strings.ToLower(part))
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

func defaultString(def any) (string, error) {
	if def == nil {
		return "", nil
	}
	s, ok := def.(string)
	if !ok {
		return "", fmt.Errorf("default %v is not a string", def)
	}
	return s, nil
}

func lower(values []string) []string {
	out := make([]string, len(values))
	for i, v := range values {
		out[i] = strings.ToLower(v)
	}
	return out
}

func stringSlice(values []string) Code {
	if len(values) == 0 {
		return Nil()
	}
	items := make([]Code, len(values))
	for i, v := range values {
		items[i] = Lit(v)
	}
	return Index().String().Values(items...)
}
